#!/usr/bin/env node
'use strict';

/**
 * DataCommand quality gate: orchestrates the Claude Code subagents in .claude/agents/.
 *
 *   Stage 0  swarm      Check that every agent definition exists and that the auditor is read-only.
 *   Stage 1  content    content-generator → OCR rubric → ocr-examiner (review and repair loop) → publish JSON.
 *   Stage 2  audit      security-qa-auditor over src/app and src/components (scanner, plus the agent with --live).
 *   Stage 3  auto-fix   While any high-severity finding remains: apply safe fixes, delegate the rest to
 *                       ui-ux-gamification (--live), then rescan. The gate fails if anything high remains.
 *   Stage 4  verify     Type-check, lint and unit tests, so fixes cannot silently break the build.
 *
 * Usage:
 *   node workflow.js                       Validate committed content and audit the UI (offline, no agents).
 *   node workflow.js --live                Also run the agents: agent audit and agent fixes (and examiner review of new content).
 *   node workflow.js --live --review       Have the ocr-examiner re-review every committed unit as well.
 *   node workflow.js --live --regenerate --spec spec.pdf
 *                                          Regenerate every unit with content-generator from the OCR spec.
 *   node workflow.js --self-test           Prove the auto-fix loop on deliberately vulnerable fixtures.
 *
 * Options:
 *   --units F200,F201         Limit the content stage to these units.
 *   --review                  With --live: the examiner re-reviews committed units, not just newly generated ones.
 *   --spec <file>             OCR specification (.pdf or .txt), giving the agents the real teaching content.
 *   --concurrency <n>         Units processed in parallel (default 4).
 *   --model <alias>           Override every agent's model (e.g. sonnet).
 *   --budget <usd>            Spend cap per agent call (default 6).
 *   --max-fix-iterations <n>  Auto-fix iterations before failing (default 3).
 *   --fix-all                 Also apply safe fixes for medium and low findings.
 *   --skip-content | --skip-audit | --skip-verify
 */

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const { validateUnit } = require('./scripts/workflow/content-rubric');
const { loadAgents, claudeCliVersion, runAgent, pool } = require('./scripts/workflow/agents');
const { loadSpecExcerpts } = require('./scripts/workflow/spec');
const { runAuditGate, scanDirs, countBySeverity } = require('./scripts/workflow/auditor');

const ROOT = __dirname;
const CONTENT_DIR = path.join(ROOT, 'src', 'content');
const UNITS_DIR = path.join(CONTENT_DIR, 'units');
const REPORT_DIR = path.join(ROOT, '.workflow');
const AUDIT_DIRS = ['src/app', 'src/components'];
const REQUIRED_AGENTS = ['content-generator', 'ocr-examiner', 'srs-specialist', 'ui-ux-gamification', 'security-qa-auditor'];
const MAX_EXAMINER_ROUNDS = 3;

// ---- CLI ------------------------------------------------------------------------------------

function parseArgs(argv) {
  const opts = {
    live: false, regenerate: false, review: false, units: null, spec: null, concurrency: 4, model: null, budget: 6,
    maxFixIterations: 3, fixAll: false, skipContent: false, skipAudit: false, skipVerify: false, selfTest: false,
  };
  const take = (i) => {
    if (argv[i + 1] === undefined) throw new Error(`${argv[i]} needs a value`);
    return argv[i + 1];
  };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    switch (arg) {
      case '--live': opts.live = true; break;
      case '--regenerate': opts.regenerate = true; break;
      case '--review': opts.review = true; break;
      case '--units': opts.units = take(i).split(',').map((u) => u.trim().toUpperCase()); i += 1; break;
      case '--spec': opts.spec = path.resolve(take(i)); i += 1; break;
      case '--concurrency': opts.concurrency = Math.max(1, Number(take(i))); i += 1; break;
      case '--model': opts.model = take(i); i += 1; break;
      case '--budget': opts.budget = Number(take(i)); i += 1; break;
      case '--max-fix-iterations': opts.maxFixIterations = Math.max(0, Number(take(i))); i += 1; break;
      case '--fix-all': opts.fixAll = true; break;
      case '--skip-content': opts.skipContent = true; break;
      case '--skip-audit': opts.skipAudit = true; break;
      case '--skip-verify': opts.skipVerify = true; break;
      case '--self-test': opts.selfTest = true; break;
      case '-h': case '--help': opts.help = true; break;
      default: throw new Error(`Unknown option ${arg} (see --help)`);
    }
  }
  if (opts.regenerate && !opts.live) throw new Error('--regenerate needs --live: content is generated by the content-generator agent.');
  if (opts.review && !opts.live) throw new Error('--review needs --live: the review is done by the ocr-examiner agent.');
  return opts;
}

// ---- Logging --------------------------------------------------------------------------------

const started = Date.now();
const color = process.stdout.isTTY ? (code) => (s) => `\x1b[${code}m${s}\x1b[0m` : () => (s) => s;
const dim = color(2); const bold = color(1); const green = color(32); const red = color(31); const yellow = color(33); const cyan = color(36);
const elapsed = () => dim(`[${((Date.now() - started) / 1000).toFixed(1).padStart(6)}s]`);
const log = (stage, message) => console.log(`${elapsed()} ${cyan(stage.padEnd(20))} ${message}`);
const heading = (title) => console.log(`\n${bold(title)}\n${dim('─'.repeat(Math.min(78, title.length + 20)))}`);

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const writeJson = (file, data) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
};

// ---- Stage 0: swarm integrity ------------------------------------------------------------

function checkSwarm(opts) {
  heading('Stage 0 · Agent swarm');
  const agents = loadAgents(ROOT);
  const problems = [];
  for (const name of REQUIRED_AGENTS) {
    const agent = agents.get(name);
    if (!agent) {
      problems.push(`missing .claude/agents/${name}.md`);
      continue;
    }
    log('swarm', `${name.padEnd(20)} model=${agent.model.padEnd(7)} tools=${agent.tools.join(',') || '(inherit)'}`);
  }
  const auditor = agents.get('security-qa-auditor');
  if (auditor && auditor.tools.some((t) => ['Write', 'Edit', 'Bash', 'NotebookEdit'].includes(t))) {
    problems.push('security-qa-auditor must be read-only (no Write/Edit/Bash tools)');
  }
  let cli = null;
  if (opts.live) {
    cli = claudeCliVersion();
    if (!cli) problems.push('--live needs the Claude Code CLI on PATH (`claude --version` failed)');
    else log('swarm', `driver: claude -p --agent <name> (${cli})`);
  } else {
    log('swarm', `driver: offline (deterministic checks only; pass --live to run the agents)`);
  }
  problems.forEach((p) => log('swarm', red(`✗ ${p}`)));
  return { ok: problems.length === 0, agents: [...agents.values()], cli, problems };
}

// ---- Stage 1: content -------------------------------------------------------------------

function unitSchema() {
  const schema = readJson(path.join(CONTENT_DIR, 'unit.schema.json'));
  delete schema.$schema;
  return schema;
}

function examinerSchema() {
  return {
    type: 'object',
    additionalProperties: false,
    required: ['verdict', 'issues', 'unit'],
    properties: {
      verdict: { type: 'string', enum: ['approved', 'revised'] },
      issues: {
        type: 'array',
        items: {
          type: 'object',
          additionalProperties: false,
          required: ['id', 'severity', 'problem', 'fix'],
          properties: {
            id: { type: 'string' },
            severity: { type: 'string', enum: ['high', 'medium', 'low'] },
            problem: { type: 'string' },
            fix: { type: 'string' },
          },
        },
      },
      unit: unitSchema(),
    },
  };
}

function blueprintBrief(blueprint, unit) {
  return [
    `Blueprint entry for ${unit.code} (copy code, title and assessment exactly):`,
    JSON.stringify(unit, null, 2),
    '',
    `OCR exam command words: ${blueprint.examCommandWords.join(', ')}.`,
    `OCR NEA command words: ${blueprint.neaCommandWords.join(', ')}.`,
  ].join('\n');
}

function specBrief(code, excerpt) {
  if (!excerpt) return 'No specification excerpt was supplied, so rely on the blueprint topic areas and your knowledge of the OCR specification.';
  return [
    `OCR specification teaching content for ${code}. This is the source of truth for scope: test only what is under "To include", and never test anything under "Does not include".`,
    '<specification>',
    excerpt,
    '</specification>',
  ].join('\n');
}

async function processUnit(bpUnit, ctx) {
  const { opts, blueprint, excerpts, agentCall } = ctx;
  const code = bpUnit.code;
  const file = path.join(UNITS_DIR, `${code}.json`);
  const record = { code, source: null, generated: false, examinerRounds: 0, examinerIssues: [], verdict: null, errors: [], warnings: [], written: false };

  let unit = fs.existsSync(file) ? readJson(file) : null;
  record.source = unit ? 'committed' : null;

  if (opts.live && (opts.regenerate || !unit)) {
    log(`content-generator`, `${code}: generating 10 flashcards + 10 exam questions…`);
    const prompt = [
      `Generate the DataCommand revision content for unit ${code}: ${bpUnit.title}.`,
      '',
      blueprintBrief(blueprint, bpUnit),
      '',
      specBrief(code, excerpts[code]),
      '',
      'Return only the unit JSON object defined in your output contract.',
    ].join('\n');
    const result = await agentCall('content-generator', prompt, unitSchema());
    if (!result.ok || !result.data) {
      record.errors.push({ rule: 'agent/content-generator', message: result.error || 'No JSON returned.' });
      log('content-generator', red(`${code}: ✗ ${result.error || 'no JSON returned'}`));
      if (!unit) return record;
    } else {
      unit = result.data;
      record.source = 'content-generator';
      record.generated = true;
      log('content-generator', `${code}: draft ready (${Math.round(result.durationMs / 1000)}s, $${result.costUsd.toFixed(2)})`);
    }
  }

  if (!unit) {
    record.errors.push({ rule: 'content/missing', message: `No ${path.relative(ROOT, file)}; run with --live to generate it.` });
    log('content', red(`${code}: ✗ no content (run with --live)`));
    return record;
  }

  let report = validateUnit(unit, bpUnit, blueprint);
  log('ocr-rubric', `${code}: ${report.errors.length ? red(`${report.errors.length} error(s)`) : green('pass')}, ${report.warnings.length} warning(s)`);

  // The examiner reviews anything generated in this run, committed units on request (--review),
  // and any committed unit the rubric now rejects.
  if (opts.live && (record.generated || opts.review || report.errors.length > 0)) {
    for (let round = 1; round <= MAX_EXAMINER_ROUNDS; round += 1) {
      // Round 1 is the examiner's full review; later rounds only repair rubric errors.
      if (round > 1 && report.errors.length === 0) break;
      record.examinerRounds = round;
      log('ocr-examiner', `${code}: ${round === 1 ? 'reviewing' : `repair round ${round}`} (${report.errors.length} rubric error(s) to fix)…`);
      const prompt = [
        `Review unit ${code} (${bpUnit.title}) as the OCR examiner${round > 1 ? '. The deterministic rubric still rejects it, so fix every listed error' : ''}.`,
        '',
        blueprintBrief(blueprint, bpUnit),
        '',
        specBrief(code, excerpts[code]),
        '',
        'Deterministic rubric report from workflow.js (you must fix every error; warnings are advisory):',
        JSON.stringify({ errors: report.errors, warnings: report.warnings }, null, 2),
        '',
        'Unit under review:',
        JSON.stringify(unit, null, 2),
        '',
        'Return only the review JSON defined in your output contract, including the complete corrected unit.',
      ].join('\n');
      const result = await agentCall('ocr-examiner', prompt, examinerSchema());
      if (!result.ok || !result.data || !result.data.unit) {
        log('ocr-examiner', red(`${code}: ✗ ${result.error || 'no review returned'}`));
        record.errors.push({ rule: 'agent/ocr-examiner', message: result.error || 'No review returned.' });
        break;
      }
      const review = result.data;
      const issues = Array.isArray(review.issues) ? review.issues : [];
      record.verdict = round === 1 ? review.verdict : 'revised';
      record.examinerIssues.push(...issues.map((issue) => ({ ...issue, round })));
      unit = review.unit;
      report = validateUnit(unit, bpUnit, blueprint);
      const bySeverity = countBySeverity(issues);
      log('ocr-examiner', `${code}: ${review.verdict} — ${issues.length} issue(s) (high ${bySeverity.high}, medium ${bySeverity.medium}, low ${bySeverity.low}); rubric ${report.errors.length ? red(`${report.errors.length} error(s)`) : green('pass')} (${Math.round(result.durationMs / 1000)}s, $${result.costUsd.toFixed(2)})`);
    }
  }

  record.errors.push(...report.errors);
  record.warnings = report.warnings;
  record.stats = report.stats;
  if (report.errors.length === 0 && (record.generated || record.examinerRounds > 0)) {
    writeJson(file, unit);
    record.written = true;
    log('publish', `${code}: wrote ${path.relative(ROOT, file)}`);
  }
  return record;
}

async function runContentStage(opts, ctx) {
  heading('Stage 1 · Content: content-generator → OCR rubric → ocr-examiner');
  const blueprint = readJson(path.join(CONTENT_DIR, 'blueprint.json'));
  const units = blueprint.units.filter((u) => !opts.units || opts.units.includes(u.code));
  if (opts.units && units.length !== opts.units.length) throw new Error(`Unknown unit in --units ${opts.units.join(',')}`);
  let excerpts = {};
  if (opts.spec) {
    excerpts = loadSpecExcerpts(opts.spec);
    log('spec', `loaded teaching content for ${Object.keys(excerpts).sort().join(', ') || 'no units'} from ${path.basename(opts.spec)}`);
  }
  const records = await pool(units, opts.concurrency, (unit) => processUnit(unit, { ...ctx, opts, blueprint, excerpts }));
  return { ok: records.every((r) => r.errors.length === 0), records };
}

// ---- Stage 2 + 3: audit and auto-fix -----------------------------------------------------

const auditFindingsSchema = {
  type: 'object',
  additionalProperties: false,
  required: ['reviewed', 'summary', 'findings'],
  properties: {
    reviewed: { type: 'array', items: { type: 'string' } },
    summary: {
      type: 'object', additionalProperties: false, required: ['high', 'medium', 'low'],
      properties: { high: { type: 'integer' }, medium: { type: 'integer' }, low: { type: 'integer' } },
    },
    findings: {
      type: 'array',
      items: {
        type: 'object', additionalProperties: false, required: ['rule', 'severity', 'file', 'line', 'evidence', 'fix'],
        properties: {
          rule: { type: 'string' }, severity: { type: 'string', enum: ['high', 'medium', 'low'] }, file: { type: 'string' },
          line: { type: 'integer' }, evidence: { type: 'string' }, fix: { type: 'string' },
        },
      },
    },
  },
};

async function runAuditStage(opts, ctx) {
  heading('Stage 2+3 · Audit and auto-fix: security-qa-auditor ⇄ ui-ux-gamification');
  const liveAuditor = opts.live ? async () => {
    const { files, findings } = scanDirs(ROOT, AUDIT_DIRS);
    const rel = files.map((f) => path.relative(ROOT, f));
    log('security-qa-auditor', `agent reviewing ${files.length} files (the scanner already found ${findings.length})…`);
    // Every file goes in the prompt with line numbers, so the agent cannot skip one and can cite exact lines.
    const sources = files.map((file, i) => {
      const numbered = fs.readFileSync(file, 'utf8').split('\n').map((line, n) => `${String(n + 1).padStart(4)}| ${line}`).join('\n');
      return `===== ${rel[i]} =====\n${numbered}`;
    });
    const prompt = [
      'Audit every DataCommand UI file below for XSS and accessibility defects, following your instructions. Use Read or Grep if you need to follow an import (for example into src/lib or src/store).',
      'The deterministic scanner has already reported the findings below, so do not repeat them. Spend your effort on issues that need judgement: untrusted data reaching the DOM or store, URL or hash parameters, focus management in dialogs, live regions, keyboard traps and misleading accessible names.',
      `Scanner findings: ${JSON.stringify(findings.map(({ fix, ...f }) => f))}`,
      'List every file you reviewed in `reviewed`. For each finding, quote `evidence` verbatim from the cited line (without the line-number prefix); findings whose evidence is not at that line are discarded. Return only the JSON defined in your output contract.',
      sources.join('\n\n'),
    ].join('\n\n');
    const result = await ctx.agentCall('security-qa-auditor', prompt, auditFindingsSchema);
    if (!result.ok || !result.data) {
      log('security-qa-auditor', yellow(`agent audit unavailable: ${result.error || 'no JSON'}; continuing with the scanner only`));
      return [];
    }
    const reviewed = new Set((result.data.reviewed || []).map((f) => f.replace(/^\.\//, '')));
    const missed = rel.filter((f) => !reviewed.has(f));
    log('security-qa-auditor', `agent reviewed ${rel.length - missed.length}/${rel.length} files and reported ${result.data.findings.length} finding(s) (${result.turns ?? '?'} turns, ${Math.round(result.durationMs / 1000)}s, $${result.costUsd.toFixed(2)})`);
    if (missed.length) log('security-qa-auditor', yellow(`agent did not confirm reviewing: ${missed.join(', ')}`));
    ctx.agentAudit = { reviewed: rel.length - missed.length, files: rel.length, findings: result.data.findings.length, missed };
    return result.data.findings;
  } : undefined;

  const fixer = opts.live ? async (findings) => {
    const prompt = [
      'workflow.js auto-fix loop: the security-qa-auditor reported the high-severity findings below, and none of them has a safe mechanical fix.',
      'Fix each one with the smallest correct change to the cited file. Keep behaviour and styling otherwise identical, keep the files valid TypeScript, and do not run shell commands.',
      JSON.stringify(findings, null, 2),
      'When you are done, reply with a one-line summary.',
    ].join('\n\n');
    const result = await ctx.agentCall('ui-ux-gamification', prompt, null, {
      allowedTools: ['Read', 'Edit', 'Write', 'Glob', 'Grep'], permissionMode: 'acceptEdits',
    });
    log('ui-ux-gamification', result.ok ? `fixer: ${String(result.text || '').split('\n')[0].slice(0, 120)}` : red(`fixer failed: ${result.error}`));
  } : undefined;

  const gate = await runAuditGate({
    root: ROOT, dirs: AUDIT_DIRS, maxIterations: opts.maxFixIterations, fixAll: opts.fixAll, liveAuditor, fixer,
    log: (message) => log('auto-fix', message),
  });
  const counts = countBySeverity(gate.findings);
  log('security-qa-auditor', `scanned ${gate.files.length} files: high ${counts.high}, medium ${counts.medium}, low ${counts.low}`);
  for (const f of gate.findings) {
    const sev = f.severity === 'high' ? red('HIGH  ') : f.severity === 'medium' ? yellow('MEDIUM') : dim('LOW   ');
    log('finding', `${sev} ${f.rule} ${f.file}:${f.line} — ${f.message || f.fix || ''}${f.source === 'agent' ? dim(' [agent]') : ''}`);
  }
  if (gate.unverified && gate.unverified.length) log('security-qa-auditor', dim(`${gate.unverified.length} agent finding(s) discarded: their evidence was not found at the cited line`));
  log('auto-fix', gate.ok
    ? green(`gate passed after ${gate.iterations.length - 1} fix iteration(s); ${gate.fixed.length} finding(s) fixed`)
    : red(`gate failed: ${gate.reason}`));
  return gate;
}

// ---- Stage 4: verify ---------------------------------------------------------------------

function runVerifyStage() {
  heading('Stage 4 · Verify: type-check, lint, unit tests');
  const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
  const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
  const checks = [
    { name: 'typecheck', cmd: npm, args: ['run', '--silent', 'typecheck'] },
    { name: 'lint', cmd: npx, args: ['eslint', '--max-warnings=0'] },
    { name: 'tests', cmd: npx, args: ['vitest', 'run', '--reporter=dot'] },
  ];
  const results = checks.map((check) => {
    const t0 = Date.now();
    const result = spawnSync(check.cmd, check.args, { cwd: ROOT, encoding: 'utf8', env: { ...process.env, CI: '1' }, maxBuffer: 32 * 1024 * 1024 });
    const ok = result.status === 0;
    const output = `${result.stdout || ''}${result.stderr || ''}`.trim();
    log('verify', `${check.name.padEnd(10)} ${ok ? green('pass') : red('FAIL')} ${dim(`(${((Date.now() - t0) / 1000).toFixed(1)}s)`)}`);
    if (!ok) console.log(output.split('\n').slice(-30).map((l) => `    ${l}`).join('\n'));
    return { name: check.name, ok, output: output.slice(-4000) };
  });
  return { ok: results.every((r) => r.ok), results };
}

// ---- Self-test ---------------------------------------------------------------------------

async function selfTest() {
  heading('Self-test · auto-fix loop on deliberately vulnerable fixtures');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'datacommand-selftest-'));
  const componentDir = path.join(dir, 'src', 'components');
  fs.mkdirSync(componentDir, { recursive: true });
  const fixture = path.join(componentDir, 'Vulnerable.tsx');
  fs.writeFileSync(fixture, `import { Trash2, X } from 'lucide-react';

export function Vulnerable({ html, query }: { html: string; query: string }) {
  const attach = (el: HTMLDivElement | null) => {
    if (el) el.innerHTML = query;
  };
  return (
    <div>
      <div className="note" dangerouslySetInnerHTML={{ __html: html }} />
      <div ref={attach} />
      <a href="javascript:alert(1)">Run</a>
      <a href="https://www.ocr.org.uk" target="_blank">OCR</a>
      <button type="button" onClick={() => undefined}><X /></button>
      <button type="button"><Trash2 size={16} /></button>
      <input type="search" placeholder="Search flashcards" />
      <span tabIndex={3}>Skip</span>
    </div>
  );
}
`);
  const checks = [];
  const expect = (name, ok) => {
    checks.push({ name, ok });
    log('self-test', `${ok ? green('✓') : red('✗')} ${name}`);
  };
  try {
    const before = scanDirs(dir, ['src/components']).findings;
    const highBefore = before.filter((f) => f.severity === 'high');
    expect(`scanner detects 6 high-severity issues (found ${highBefore.length})`, highBefore.length === 6);
    const gate = await runAuditGate({ root: dir, dirs: ['src/components'], log: (m) => log('auto-fix', m) });
    const fixedText = fs.readFileSync(fixture, 'utf8');
    expect('auto-fix loop clears every high-severity finding', gate.ok);
    expect('dangerouslySetInnerHTML is rendered as text', fixedText.includes('<div className="note">{html}</div>'));
    expect('innerHTML assignment becomes textContent', fixedText.includes('el.textContent = query'));
    expect('icon-only buttons gain aria-labels', fixedText.includes('aria-label={"Close"}') && fixedText.includes('aria-label={"Delete"}'));
    expect('search input is labelled from its placeholder', fixedText.includes('aria-label={"Search flashcards"}'));
    expect('medium/low findings are reported but not blocking', gate.findings.some((f) => f.rule === 'security/reverse-tabnabbing'));

    fs.writeFileSync(path.join(componentDir, 'Evaluator.tsx'), 'export const run = (code: string) => eval(code);\n');
    const failing = await runAuditGate({ root: dir, dirs: ['src/components'], log: () => {} });
    expect('gate fails closed on a high finding with no safe fix (eval)', !failing.ok);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
  return { ok: checks.every((c) => c.ok), checks };
}

// ---- Main --------------------------------------------------------------------------------

function writeReports(report) {
  writeJson(path.join(REPORT_DIR, 'report.json'), report);
  const lines = [`# DataCommand quality gate — ${report.ok ? 'PASSED' : 'FAILED'}`, '', `Run: ${report.finishedAt} · mode: ${report.mode}`, ''];
  if (report.content) {
    lines.push('## Content', '', '| Unit | Source | Examiner | Rubric errors | Warnings | Written |', '| --- | --- | --- | --- | --- | --- |');
    for (const r of report.content.records) {
      lines.push(`| ${r.code} | ${r.source} | ${r.verdict ? `${r.verdict} (${r.examinerIssues.length} issues, ${r.examinerRounds} round(s))` : 'rubric only'} | ${r.errors.length} | ${r.warnings.length} | ${r.written ? 'yes' : 'no'} |`);
    }
    lines.push('');
  }
  if (report.audit) {
    const c = countBySeverity(report.audit.findings);
    lines.push('## Audit', '', `High ${c.high} · Medium ${c.medium} · Low ${c.low} · fixed ${report.audit.fixed.length}`, '');
    report.audit.findings.forEach((f) => lines.push(`- **${f.severity}** \`${f.rule}\` ${f.file}:${f.line} — ${f.message || f.fix || ''}`));
    lines.push('');
  }
  if (report.verify) lines.push('## Verify', '', ...report.verify.results.map((r) => `- ${r.name}: ${r.ok ? 'pass' : 'FAIL'}`), '');
  fs.writeFileSync(path.join(REPORT_DIR, 'report.md'), `${lines.join('\n')}\n`);
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.help) {
    console.log(fs.readFileSync(__filename, 'utf8').split('*/')[0].replace(/^#!.*\n'use strict';\n\n\/\*\*\n/, '').replace(/^ \* ?/gm, ''));
    return;
  }
  console.log(bold(`DataCommand workflow · ${opts.selfTest ? 'self-test' : opts.live ? 'live agents' : 'offline'}`));
  if (opts.selfTest) {
    const result = await selfTest();
    console.log(`\n${result.ok ? green('Self-test passed') : red('Self-test failed')}`);
    process.exitCode = result.ok ? 0 : 1;
    return;
  }

  let spend = 0;
  let calls = 0;
  const ctx = {
    agentCall: async (agent, prompt, jsonSchema, extra = {}) => {
      calls += 1;
      const result = await runAgent({ agent, prompt, cwd: ROOT, jsonSchema, model: opts.model, maxBudgetUsd: opts.budget, ...extra });
      spend += result.costUsd || 0;
      return result;
    },
  };

  const report = { mode: opts.live ? 'live' : 'offline', startedAt: new Date(started).toISOString() };
  const swarm = checkSwarm(opts);
  report.swarm = swarm;
  let ok = swarm.ok;
  if (ok && !opts.skipContent) {
    report.content = await runContentStage(opts, ctx);
    ok = ok && report.content.ok;
  }
  if (swarm.ok && !opts.skipAudit) {
    report.audit = await runAuditStage(opts, ctx);
    ok = ok && report.audit.ok;
  }
  if (swarm.ok && !opts.skipVerify) {
    report.verify = runVerifyStage();
    ok = ok && report.verify.ok;
  }

  report.ok = ok;
  report.agentCalls = calls;
  report.agentSpendUsd = Number(spend.toFixed(4));
  report.finishedAt = new Date().toISOString();
  writeReports(report);

  heading('Summary');
  if (report.content) {
    for (const r of report.content.records) {
      const status = r.errors.length ? red('✗') : green('✓');
      const examiner = r.verdict ? `examiner ${r.verdict} (${r.examinerIssues.length} issue(s))` : 'rubric only';
      log('content', `${status} ${r.code}  source=${r.source}  ${examiner}  errors=${r.errors.length} warnings=${r.warnings.length}${r.written ? '  → written' : ''}`);
      r.errors.slice(0, 8).forEach((e) => log('content', red(`    ${e.id ? `${e.id} ` : ''}${e.rule}: ${e.message}`)));
    }
  }
  if (report.audit) log('audit', `${report.audit.ok ? green('✓ no high-severity findings') : red(`✗ ${report.audit.reason}`)}`);
  if (report.verify) log('verify', report.verify.ok ? green('✓ typecheck, lint and tests pass') : red('✗ see failures above'));
  if (opts.live) log('agents', `${calls} agent call(s), $${spend.toFixed(2)} total`);
  log('report', `${path.relative(ROOT, path.join(REPORT_DIR, 'report.md'))}`);
  console.log(`\n${ok ? green(bold('QUALITY GATE PASSED')) : red(bold('QUALITY GATE FAILED'))}`);
  process.exitCode = ok ? 0 : 1;
}

main().catch((err) => {
  console.error(red(`workflow failed: ${err.stack || err.message}`));
  process.exitCode = 1;
});
